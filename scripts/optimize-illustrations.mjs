// Turns José's original illustrations (assets-source/illustrations/) into web
// images in public/illustrations/, and writes lib/illustration-images.ts with
// their paths and pixel sizes so the code never hard-codes dimensions.
//
// Two sizes per piece:
//   <slug>-card.webp  the grid card. Light, so the gallery doesn't pull megabytes.
//   <slug>.webp       the detail view. Long side capped at FULL_MAX.
//
// Run with: npm run optimize:illustrations
// To add or swap a piece: drop the original in assets-source/illustrations/,
// add/adjust its line in SOURCES, run the script, then give it copy in
// lib/illustrations.ts.
import sharp from "sharp";
import { mkdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";

const SRC = "assets-source/illustrations";
const OUT = "public/illustrations";
const MODULE_OUT = "lib/illustration-images.ts";

/** slug -> original file. The slug names the outputs and keys lib/illustrations.ts. */
const SOURCES = [
  { slug: "aurora", file: "aurorasplashart.jpg" },
  { slug: "tigre", file: "Tigre.png" },
  { slug: "poki", file: "Poki.png" },
  { slug: "whitebird", file: "Whitebird.png" },
  { slug: "sacred", file: "sacred rep 13.png" },
];

const FULL_MAX = 2000; // px, long side
const CARD_WIDTH = { portrait: 800, landscape: 1600 }; // px; a landscape card spans two columns

await mkdir(OUT, { recursive: true });

const manifest = {};
let before = 0;
let after = 0;

for (const { slug, file } of SOURCES) {
  const input = path.join(SRC, file);
  const original = (await stat(input)).size;
  before += original;

  // Some originals are huge (5000x5800), so lift sharp's pixel-count safety limit.
  const source = () => sharp(input, { limitInputPixels: false }).rotate().removeAlpha();

  const { width: srcWidth, height: srcHeight } = await sharp(input, {
    limitInputPixels: false,
  }).metadata();
  const orientation = srcWidth > srcHeight ? "landscape" : "portrait";

  const full = await source()
    .resize({ width: FULL_MAX, height: FULL_MAX, fit: "inside", withoutEnlargement: true })
    .webp({ quality: 86, effort: 6, smartSubsample: true })
    .toFile(path.join(OUT, `${slug}.webp`));

  const card = await source()
    .resize({ width: CARD_WIDTH[orientation], withoutEnlargement: true })
    .webp({ quality: 80, effort: 6, smartSubsample: true })
    .toFile(path.join(OUT, `${slug}-card.webp`));

  after += full.size + card.size;
  manifest[slug] = {
    card: `/illustrations/${slug}-card.webp`,
    full: `/illustrations/${slug}.webp`,
    width: full.width,
    height: full.height,
  };

  console.log(
    `${slug.padEnd(10)} ${srcWidth}x${srcHeight} ${(original / 1024 / 1024).toFixed(2)} MB -> ` +
      `full ${full.width}x${full.height} ${(full.size / 1024).toFixed(0)} KB, ` +
      `card ${card.width}x${card.height} ${(card.size / 1024).toFixed(0)} KB`,
  );
}

const body = Object.entries(manifest)
  .map(
    ([slug, m]) =>
      `  ${slug}: { card: "${m.card}", full: "${m.full}", width: ${m.width}, height: ${m.height} },`,
  )
  .join("\n");

await writeFile(
  MODULE_OUT,
  `// Generated by scripts/optimize-illustrations.mjs (npm run optimize:illustrations). Do not edit by hand.\n` +
    `// width/height are those of the "full" image; the card image has the same aspect ratio.\n` +
    `export const ILLUSTRATION_IMAGES = {\n${body}\n} as const;\n`,
);

console.log(`total: ${(before / 1024 / 1024).toFixed(1)} MB -> ${(after / 1024 / 1024).toFixed(2)} MB`);
console.log(`wrote ${MODULE_OUT}`);
